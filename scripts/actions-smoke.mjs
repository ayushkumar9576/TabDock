// Run against the disposable browser profile used by browser-smoke.mjs.
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { connect, poll } from "./cdp.mjs";
const server = createServer((request, response) => { response.writeHead(200, { "content-type": "text/html" }); response.end("<title>Action test</title>"); });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const site = `http://127.0.0.1:${server.address().port}`;
let connection;
try {
  const connected = await connect(); connection = connected.connection;
  const target = await connection.send("Target.createTarget", { url: `${connected.base}popup/popup.html` });
  const { sessionId } = await connection.send("Target.attachToTarget", { targetId: target.targetId, flatten: true });
  await connection.send("Runtime.enable", {}, sessionId);
  const evaluate = expression => connection.evaluate(sessionId, expression);
  const ready = () => poll(() => evaluate("document.body?.dataset.ready==='true' && !document.body.hasAttribute('aria-busy')"));
  async function call(type, payload = {}) {
    const response = await evaluate(`chrome.runtime.sendMessage(${JSON.stringify({ ...payload, type })})`);
    assert.equal(response.ok, true, response.error); return response.data;
  }
  await ready();
  await evaluate("chrome.storage.local.set({tabHarbor:{version:1,groups:[],pendingMoves:[],undo:[],settings:{removeAfterOpen:false}}})");
  const solo = await call("SAVE_PAGE", { url: `${site}/solo`, title: "Solo" });
  const kept = await call("SAVE_PAGE", { url: `${site}/kept`, title: "Keep test" });
  await call("CREATE_GROUP", { name: "Delete test" });
  const group = (await call("GET_STATE")).groups.find(item => item.name === "Delete test");
  const child = await call("SAVE_PAGE", { groupId: group.id, url: `${site}/child`, title: "Child" });
  await call("SAVE_PAGE", { groupId: group.id, url: `${site}/other`, title: "Other child" });
  await poll(() => evaluate("document.querySelectorAll('.tab-remove').length===4"));
  const beforeTabs = await evaluate("chrome.tabs.query({}).then(tabs=>tabs.length)");
  await evaluate(`document.querySelector('[data-link-id="${solo.linkId}"] .tab-remove').focus()`);
  await connection.send("Input.dispatchKeyEvent", { type: "keyDown", key: "Enter", code: "Enter", text: "\r", windowsVirtualKeyCode: 13 }, sessionId);
  await connection.send("Input.dispatchKeyEvent", { type: "keyUp", key: "Enter", code: "Enter", windowsVirtualKeyCode: 13 }, sessionId);
  await poll(async () => !(await call("GET_STATE")).groups.some(item => item.id === solo.groupId));
  await ready();
  assert.equal(await evaluate("chrome.tabs.query({}).then(tabs=>tabs.length)"), beforeTabs);
  await evaluate(`document.querySelector('[data-link-id="${child.linkId}"] .tab-remove').click()`);
  await poll(async () => (await call("GET_STATE")).groups.find(item => item.id === group.id).links.length === 1);
  await ready();
  await evaluate(`document.querySelector('.tab-group[data-entry-id="${group.id}"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:50,clientY:120}))`);
  assert.deepEqual(await evaluate("[...document.querySelectorAll('#context-menu button')].map(node=>node.textContent)"), ["Open", "Delete group"]);
  await evaluate("document.querySelector('.menu-danger').click()");
  await poll(async () => !(await call("GET_STATE")).groups.some(item => item.id === group.id));
  await ready();
  await evaluate("document.querySelector('#settings-toggle').click();document.querySelector('#remove-after-open').click()");
  await poll(async () => (await call("GET_STATE")).settings.removeAfterOpen);
  await evaluate("document.querySelector('#settings-close').click()");
  await connection.send("Page.reload", {}, sessionId); await ready();
  assert.equal(await evaluate("document.querySelector('#remove-after-open').checked"), true);
  await call("OPEN_LINK", { groupId: kept.groupId, linkId: kept.linkId });
  assert.ok(!(await call("GET_STATE")).groups.some(item => item.id === kept.groupId));
  await call("CREATE_GROUP", { name: "Open test" });
  const opening = (await call("GET_STATE")).groups.find(item => item.name === "Open test");
  for (let n = 1; n <= 2; n++)await call("SAVE_PAGE", { groupId: opening.id, url: `${site}/open${n}`, title: `Page ${n}` });
  const opened = await call("OPEN_GROUP", { groupId: opening.id });
  assert.equal(opened.tabIds.length, 2); assert.ok(!(await call("GET_STATE")).groups.some(item => item.id === opening.id));
  await call("UPDATE_SETTINGS", { removeAfterOpen: false });
  const retained = await call("SAVE_PAGE", { url: `${site}/retained`, title: "Retained" });
  await call("OPEN_LINK", { groupId: retained.groupId, linkId: retained.linkId });
  assert.ok((await call("GET_STATE")).groups.some(item => item.id === retained.groupId));
  await connection.send("Page.navigate", { url: "http://127.0.0.1:5173" }, sessionId);
  await poll(() => evaluate("document.querySelector('#popup')?.contentDocument?.body?.dataset.ready==='true'"));
  const preview = code => evaluate(`document.querySelector('#popup').contentWindow.eval(${JSON.stringify(code)})`);
  await evaluate("document.querySelector('[data-fixture=default]').click()");
  await poll(() => preview("document.querySelectorAll('.tab-card').length===6"));
  await preview("document.querySelector('.tab-remove').click()");
  await poll(() => preview("document.querySelectorAll('.tab-card').length===5"));
  await preview("document.querySelector('.tab-group').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:50,clientY:50}));document.querySelector('.menu-danger').click()");
  await poll(() => preview("document.querySelectorAll('.tab-group').length===1"));
  await preview("document.querySelector('#settings-toggle').click();if(!document.querySelector('#remove-after-open').checked)document.querySelector('#remove-after-open').click()");
  await poll(() => preview("document.querySelector('#remove-after-open').checked && !document.body.hasAttribute('aria-busy')"));
  await preview("document.querySelector('#settings-close').click();document.querySelector('.tab-group').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:50,clientY:50}));document.querySelector('#context-menu button').click()");
  await poll(() => preview("document.querySelectorAll('.tab-group').length===0"));
  await preview("document.querySelector('#settings-toggle').click();document.querySelector('#remove-after-open').click()");
  await poll(() => preview("!document.querySelector('#remove-after-open').checked && !document.body.hasAttribute('aria-busy')"));
  await preview("document.querySelector('#settings-close').click()");
  await evaluate("document.querySelector('[data-fixture=default]').click()");
  await poll(() => preview("document.querySelectorAll('.tab-card').length===6"));
  assert.deepEqual(connection.events.filter(event => event.method === "Runtime.exceptionThrown"), []);
  console.log("PASS: red cross deletion (mouse and keyboard), whole-group deletion, saved opening preference, keep/remove behavior, and matching preview controls.");
  if (process.argv.includes("--close")) await connection.send("Browser.close");
} finally { connection?.close(); await new Promise(resolve => server.close(resolve)); }
